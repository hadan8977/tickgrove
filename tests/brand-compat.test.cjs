const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
require('../scripts/register-typescript.cjs');
const { compatibleStorage } = require('../src/brand/storage.ts');
const { fromPine, toPine } = require('../src/builder/codegen.ts');
function storage(entries = {}) {
  const values = new Map(Object.entries(entries));
  return { getItem: k => values.get(k) ?? null, setItem: (k,v) => values.set(k,v), removeItem: k => values.delete(k) };
}
test('existing browser state is copied without changing the saved document', () => {
  const document = JSON.stringify({state:{theme:'moss',charts:{saved:{symbol:'COINBASE:SOL-USD'}}},version:0});
  const raw=storage({'oc.charts':document}), upgraded=compatibleStorage(raw);
  assert.equal(upgraded.getItem('tickgrove.charts'),document);
  assert.equal(raw.getItem('tickgrove.charts'),document);
  assert.equal(raw.getItem('oc.charts'),document);
  upgraded.setItem('tickgrove.charts','new');
  assert.equal(upgraded.getItem('tickgrove.charts'),'new');
});
test('current empty values win; removal cannot revive a legacy session token', () => {
  const raw=storage({'trading.token':'legacy-fixture','tickgrove.token':''});
  const upgraded=compatibleStorage(raw,'trading.');
  assert.equal(upgraded.getItem('tickgrove.token'),'');
  upgraded.removeItem('tickgrove.token');
  assert.equal(upgraded.getItem('tickgrove.token'),null);
  assert.equal(raw.getItem('trading.token'),null);
});
test('full storage still permits loading the old saved state', () => {
  const raw=storage({'oc.app':'legacy'});raw.setItem=()=>{throw Error('quota')};
  assert.equal(compatibleStorage(raw).getItem('tickgrove.app'),'legacy');
});
test('actual pre-rename builder output still reopens; edited strategies remain rejected', () => {
  const legacy=fs.readFileSync('tests/fixtures/builder-legacy-brand.pine','utf8');
  const result=fromPine(legacy);
  assert.equal(result.ok,true);
  assert.equal(result.def.name,'Saved before Tickgrove');
  const current=toPine(result.def);
  assert.match(current,/Generated by Tickgrove/);
  assert.match(current,/@tickgrove-blocks/);
  assert.deepEqual(fromPine(current),result);
  assert.equal(fromPine(legacy.replace('close > sma20','close < sma20')).ok,false);
});
